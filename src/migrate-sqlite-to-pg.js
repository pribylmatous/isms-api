// Jednorázový přenos dat ze staré SQLite databáze (isms.db) do PostgreSQL.
// Spuštění: node src/migrate-sqlite-to-pg.js  (poté, co DATABASE_URL v .env
// ukazuje na čerstvě založenou/prázdnou Postgres DB se schématem — to založí
// samo openDb() při prvním připojení, stejně jako běžný start serveru).
//
// Nemigruje 'sessions' (krátkodobé, po cutover se všichni prostě znovu
// přihlásí — to je při přechodu na jinou DB očekávané).
//
// Čte SQLite napřímo přes node:sqlite (ne přes src/db.js, který je teď na
// Postgres) — nezávislé na zbytku appky, jednorázový nástroj.

import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from './env.js';
import { openDb } from './db.js';

loadEnv();

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const sqlitePath = process.argv[2] ?? path.join(__dirname, '..', 'isms.db');

// Pořadí respektuje FK vazby — rodiče (controls/risks/trainings/users) před
// dětmi (changes/incidents/training_completions/audit_log), na rozdíl od
// TABLE_ORDER v db.js (to je pořadí pro mazání, ne pro vkládání).
const MIGRATE_ORDER = [
  'users', 'controls', 'risks', 'policies', 'audit_findings', 'changes', 'incidents',
  'trainings', 'training_completions', 'faqs', 'deadlines', 'settings', 'audit_log', 'notifications',
];
// Tabulky s INTEGER GENERATED BY DEFAULT AS IDENTITY — po vložení explicitních
// id je potřeba posunout sekvenci, jinak by další INSERT bez id kolidoval.
const IDENTITY_TABLES = new Set([
  'policies', 'trainings', 'training_completions', 'faqs', 'deadlines', 'users', 'audit_log', 'notifications',
]);

console.log(`Zdroj: ${sqlitePath}`);
const sqlite = new DatabaseSync(sqlitePath, { readOnly: true });
const pg = await openDb();

let totalRows = 0;
for (const table of MIGRATE_ORDER) {
  const rows = sqlite.prepare(`SELECT * FROM ${table}`).all();
  for (const row of rows) {
    const columns = Object.keys(row);
    const placeholders = columns.map(() => '?').join(', ');
    await pg.prepare(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${placeholders})`)
      .run(...columns.map((c) => row[c]));
  }
  if (IDENTITY_TABLES.has(table)) {
    await pg.exec(`SELECT setval(pg_get_serial_sequence('${table}', 'id'),
      COALESCE((SELECT MAX(id) FROM ${table}), 1), (SELECT MAX(id) FROM ${table}) IS NOT NULL)`);
  }
  console.log(`  ${table}: ${rows.length} řádků`);
  totalRows += rows.length;
}

console.log(`\nHotovo — přeneseno ${totalRows} řádků celkem.`);
sqlite.close();
await pg.close();
